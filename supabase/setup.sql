-- ChatWave MVP: public shared chat.
-- This deliberately allows anyone with the public anon key to read and post.
-- Do not store sensitive conversations in this prototype.

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  author_name text not null check (char_length(author_name) between 2 and 24),
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

drop policy if exists "Anyone can read ChatWave messages" on public.messages;
create policy "Anyone can read ChatWave messages"
  on public.messages for select to anon, authenticated
  using (true);

drop policy if exists "Anyone can post ChatWave messages" on public.messages;
create policy "Anyone can post ChatWave messages"
  on public.messages for insert to anon, authenticated
  with check (
    char_length(author_name) between 2 and 24
    and char_length(body) between 1 and 2000
  );

grant select, insert on public.messages to anon, authenticated;
grant usage, select on sequence public.messages_id_seq to anon, authenticated;

